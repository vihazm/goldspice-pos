    private void addItemToBill() {
    try {
        int productId = Integer.parseInt(ProductIdIn.getText().trim());
        int quantity = Integer.parseInt(QuantityIn.getText().trim());

        if (quantity <= 0) {
            JOptionPane.showMessageDialog(this, "Please enter a valid quantity.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        Product product = billController.getProductDetails(productId);

        if (product != null) {
            double subtotal = quantity * product.getP_price();

            Object[] rowData = {product.getP_id(), product.getP_name(), quantity, product.getP_price(), subtotal};
            tableModel.addRow(rowData);

            calculateTotal();
            ProductIdIn.setText("");
            QuantityIn.setText("");
        } else {
            JOptionPane.showMessageDialog(this, "Product not found. Please enter a valid Product ID.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Please enter valid numbers for Product ID and Quantity.", "Input Error", JOptionPane.ERROR_MESSAGE);
    }
}

    private void removeItemFromBill() {
    int selectedRow = bill_items.getSelectedRow();
    if (selectedRow != -1) {
        tableModel.removeRow(selectedRow);
        calculateTotal();
    } else {
        JOptionPane.showMessageDialog(this, "Please select an item to remove.", "Selection Error", JOptionPane.ERROR_MESSAGE);
    }
}
    
    private void calculateTotal() {
    double total = 0.0;
    for (int i = 0; i < tableModel.getRowCount(); i++) {
        Object val = tableModel.getValueAt(i, 4); // Subtotal column
        if (val instanceof Number) {
            total += ((Number) val).doubleValue();
        }
    }
    TotalPriceViewLabel.setText(String.format("%.2f", total));
    }

    private void createBill() {
    String customerName = CustomerNameIn.getText().trim();
    String billDate = BillDateIn.getText().trim();

    double totalAmount;
    try {
        totalAmount = Double.parseDouble(TotalPriceViewLabel.getText());
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Invalid total amount.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    if (customerName.isEmpty() || billDate.isEmpty() || totalAmount <= 0 || tableModel.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this, "Please fill in all fields and add items to the bill.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    Vector<Vector> billItemsData = tableModel.getDataVector();
    boolean success = billController.saveBill(customerName, billDate, totalAmount, this.cashierId, billItemsData);

    if (success) {
        JOptionPane.showMessageDialog(this, "Bill created successfully!");
        CustomerNameIn.setText("");
        BillDateIn.setText("");
        tableModel.setRowCount(0);
        calculateTotal();
    } else {
        JOptionPane.showMessageDialog(this, "Failed to create bill. Please try again.", "Database Error", JOptionPane.ERROR_MESSAGE);
    }
    }
    
