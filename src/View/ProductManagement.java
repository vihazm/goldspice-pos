    private void AddProductBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddProductBtnActionPerformed
        try {
        int pId = Integer.parseInt(ProductIdIn.getText());
        String pName = ProductNameIn.getText();
        double pPrice = Double.parseDouble(ProductPriceIn.getText());
        int stockLevel = Integer.parseInt(StockLevelIn.getText());

        if (pName.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Product name cannot be empty.", "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (productController.addProduct(pId, pName, pPrice, stockLevel)) {
            JOptionPane.showMessageDialog(this, "Product added successfully!");
            clearInputFields(); // Clear the fields after success
            loadTableData();    // Refresh the table
        } else {
            JOptionPane.showMessageDialog(this, "Failed to add product.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Please enter valid numbers for Product ID, Price, and Stock Level.", "Input Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_AddProductBtnActionPerformed

    private void DeleteProductBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteProductBtnActionPerformed
        try {
        // Get the product ID from the text field
        int pId = Integer.parseInt(DeleteProductIdIn.getText());
        
        // Add a confirmation dialog for user safety
        int confirm = JOptionPane.showConfirmDialog(this, 
            "Are you sure you want to delete product with ID: " + pId + "?", 
            "Confirm Deletion", JOptionPane.YES_NO_OPTION);
            
        if (confirm == JOptionPane.YES_OPTION) {
            // Call the delete method from the controller
            if (productController.deleteProduct(pId)) {
                JOptionPane.showMessageDialog(this, "Product deleted successfully!");
                DeleteProductIdIn.setText(""); // Clear the input field
                loadTableData(); // Refresh the table
            } else {
                JOptionPane.showMessageDialog(this, "Failed to delete product. It may not exist.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Please enter a valid number for the Product ID.", "Input Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_DeleteProductBtnActionPerformed
    
