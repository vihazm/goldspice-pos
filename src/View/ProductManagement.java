    private void EditProductBtnActionPerformed(java.awt.event.ActionEvent evt) {
        try {
            int pId = Integer.parseInt(ProductIdIn.getText());
            String pName = ProductNameIn.getText();
            double pPrice = Double.parseDouble(ProductPriceIn.getText());
            int stockLevel = Integer.parseInt(StockLevelIn.getText());

            if (pName.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Product name cannot be empty.", "Input Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Call the edit method from the controller
            if (productController.editProduct(pId, pName, pPrice, stockLevel)) {
                JOptionPane.showMessageDialog(this, "Product updated successfully!");
                clearInputFields(); // Clear the fields after success
                loadTableData();    // Refresh the table
            } else {
                JOptionPane.showMessageDialog(this, "Failed to edit product. The ID might not exist.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter valid numbers for Product ID, Price, and Stock Level.", "Input Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    
