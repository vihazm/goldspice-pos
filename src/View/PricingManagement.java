// Method to load all products into the table
    private void loadTableData() {
        // Clear existing data from the table
    tableModel.setRowCount(0);
    // This single line calls the method in the controller to handle data loading
    productController.loadProducts(tableModel);
    }
    
        private void searchKeyReleased(java.awt.event.KeyEvent evt) {
        String searchName = ProductNameIn.getText().trim().toLowerCase();

        // Clear existing data from the table
        tableModel.setRowCount(0);

        try (java.sql.ResultSet rs = productController.getAllProducts()) {
            while (rs.next()) {
                String productName = rs.getString("P_name").toLowerCase();
                // Check if the product name contains the search text
                if (productName.contains(searchName)) {
                    tableModel.addRow(new Object[]{
                        rs.getInt("P_id"),
                        rs.getString("P_name"),
                        rs.getDouble("P_price"),
                        rs.getInt("StockLevel")
                    });
                }
            }
        } catch (java.sql.SQLException e) {
            JOptionPane.showMessageDialog(this, "Error searching for product: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }

