    // Method to handle the edit product button action
    private void EditProductBtnActionPerformed(java.awt.event.ActionEvent evt) {
        try {
            // Get product name from the search field
            String productName = ProductNameIn.getText().trim();
            // Get new price from the price field
            double newPrice = Double.parseDouble(ProductPriceIn.getText().trim());

            if (productName.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter a product name to update.", "Input Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            try {
                // Call the new controller method to update by name
                if (productController.updateProductPriceByName(productName, newPrice)) {
                    JOptionPane.showMessageDialog(this, "Product price updated successfully!");
                    loadTableData(); // Refresh the table to show the new price
                    ProductNameIn.setText("");
                    ProductPriceIn.setText("");
                } else {
                    JOptionPane.showMessageDialog(this, "Failed to update price. The product name might not exist.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "A database error occurred: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
                e.printStackTrace();
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid number for the New Price.", "Input Error", JOptionPane.ERROR_MESSAGE);
        }
    }
