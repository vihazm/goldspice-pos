    private void AddUserBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddUserBtnActionPerformed
        try {
            int userId = Integer.parseInt(UserIdIn.getText());
            String userName = NameIn.getText();
            String username = UsernameIn.getText();
            String password = PasswordIn.getText();
            String userRole = UserRoleIn.getText();
            String joinDate = JoinDateIn.getText();

            // Input validation
            if (userName.isEmpty() || username.isEmpty() || password.isEmpty() || userRole.isEmpty() || joinDate.isEmpty()) {
                JOptionPane.showMessageDialog(this, "All fields must be filled.", "Input Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Corrected method call with the correct variable names
            if (userController.addUser(userId, userName, username, password, userRole, joinDate)) {
                JOptionPane.showMessageDialog(this, "User added successfully!");
                clearInputFields(); // Clear fields after success
                loadTableData();    // Refresh the table
            } else {
                JOptionPane.showMessageDialog(this, "Failed to add user. Check for duplicate User ID or User Name.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter a valid number for User ID.", "Input Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_AddUserBtnActionPerformed

