    private void loadAllBills() {
        tableModel.setRowCount(0); // Clear existing data
        DefaultTableModel allBillsModel = billController.getAllBills();
        // Copy rows from the model returned by controller to the tableModel used by JTable
        for (int i = 0; i < allBillsModel.getRowCount(); i++) {
            tableModel.addRow((Vector) allBillsModel.getDataVector().elementAt(i));
        }
    }

    /**
     * Sorts bills based on the selected quarter from the JComboBox.
     */
    private void sortBillsByQuarter() {
        String selectedQuarter = (String) QuarterScrollBox.getSelectedItem();
        tableModel.setRowCount(0); // Clear existing data

        // Use equals() to check for the exact string, including "All Quarters"
        if ("All Quarters".equals(selectedQuarter)) {
            loadAllBills();
        } else {
            int quarter = 0;
            // Check for the full string to determine the quarter number
            if ("Jan - Mar".equals(selectedQuarter)) {
                quarter = 1;
            } else if ("Apr - Jun".equals(selectedQuarter)) {
                quarter = 2;
            } else if ("Jul - Sep".equals(selectedQuarter)) {
                quarter = 3;
            } else if ("Oct - Dec".equals(selectedQuarter)) {
                quarter = 4;
            }
            
            // Call the updated controller method
            DefaultTableModel filteredBillsModel = billController.getBillsByQuarter(quarter);
            for (int i = 0; i < filteredBillsModel.getRowCount(); i++) {
                tableModel.addRow((Vector) filteredBillsModel.getDataVector().elementAt(i));
            }
        }
    }
    
